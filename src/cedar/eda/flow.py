def conformal_lec(ctx: FlowContext, golden: Sequence[str], revised: Sequence[str], work: Path,
                  extra: Sequence[str] = (), timeout: Optional[int] = None) -> StageResult:
    """RTL-to-RTL equivalence (golden = original design). Fail-closed parsing."""
    work.mkdir(parents=True, exist_ok=True)
    fmt_g = "-systemverilog" if detect_hdl(golden) == "sverilog" else "-verilog"
    fmt_r = "-systemverilog" if detect_hdl(revised) == "sverilog" else "-verilog"
    tech_extra = (ctx.tech.data.get("equivalence") or {}).get("extra_commands") or []
    # Verilog command files carry the design's include dirs and defines so the
    # checked configuration is exactly the synthesized one.
    common = [f"+incdir+{d}" for d in ctx.include_dirs]
    common += [f"+define+{k}={v}" if v not in (None, "") else f"+define+{k}" for k, v in ctx.defines.items()]
    (work / "golden.f").write_text("\n".join(common + list(golden)) + "\n")
    (work / "revised.f").write_text("\n".join(common + list(revised)) + "\n")
    lines = [
        "set log file lec.log -replace",
        f"read design -file golden.f -golden {fmt_g}",
        f"read design -file revised.f -revised {fmt_r}",
        f"set root module {ctx.top} -golden",
        f"set root module {ctx.top} -revised",
        *tech_extra, *extra,
        "set system mode lec",
        "add compared points -all",
        "compare",
        "report compare data -summary > compare_summary.rpt",
        "report unmapped points -summary > unmapped.rpt",
        "report verification > verification.rpt",
        "exit -force",
    ]
    (work / "lec.do").write_text("\n".join(lines) + "\n")
    started = _clear(work, ["verification.rpt", "compare_summary.rpt", "unmapped.rpt", "lec.log", "conformal.log"])
    r = ctx.tools.run("equivalence", ["-nogui", "-dofile", str(work / "lec.do")], work, work / "conformal.log",
                      timeout, stdin_text="", label="equivalence")
    r.outputs = {"verification_rpt": str(work / "verification.rpt"), "log": str(work / "conformal.log"),
                 "started_at": repr(started)}
    return r


def parse_conformal(r: StageResult) -> Dict[str, object]:
    """Return {'status': passed|failed|unavailable|error, 'detail':..., 'points':...}.

    ``passed`` requires a successful process (exit 0) AND fresh report evidence
    written by this invocation. A failed process can at most confirm a
    non-equivalence (``failed``); otherwise it is an ``error``.
    """
    if r.status == "unavailable":
        return {"status": "unavailable", "detail": r.detail}
    if r.status == "timeout":
        return {"status": "error", "detail": f"Conformal timed out: {r.detail}"}
    started = float(r.outputs.get("started_at", "0") or 0)
    logp = Path(r.outputs.get("log", r.log))
    ver = Path(r.outputs["verification_rpt"])
    fresh_log = _fresh(logp, started)
    fresh_ver = _fresh(ver, started)
    log = logp.read_text(errors="replace") if fresh_log else ""
    vtxt = ver.read_text(errors="replace") if fresh_ver else ""
    m = re.search(r"Compare Results:\s+(\w+)", vtxt)
    inc = re.search(r"Incomplete verification:\s+(\d+)", vtxt)
    eq = re.search(r"^Equivalent\s+.*?(\d+)\s*$", log, re.M)
    neq = re.search(r"^Non-equivalent\s+.*?(\d+)\s*$", log, re.M)
    ab = re.search(r"^Abort\s+.*?(\d+)\s*$", log, re.M)
    points = int(eq.group(1)) if eq else 0
    says_fail = (m is not None and m.group(1) != "PASS") or bool(neq and int(neq.group(1)) > 0)
    if r.status != "ok":
        if says_fail:
            return {"status": "failed", "detail": f"Conformal reported non-equivalence (exit {r.returncode})"
                    f"{'; non-equivalent ' + neq.group(1) if neq else ''}", "points": points}
        return {"status": "error", "detail": f"Conformal process failed (status {r.status}, exit {r.returncode}); "
                "report evidence is not accepted", "points": points}
    if not fresh_ver or not fresh_log:
        return {"status": "error", "detail": "no verification report/log written by this Conformal invocation",
                "points": points}
    if not m:
        return {"status": "error", "detail": "no 'Compare Results' in verification report", "points": points}
    if m.group(1) != "PASS":
        return {"status": "failed", "detail": f"Compare Results: {m.group(1)}"
                f"{'; non-equivalent ' + neq.group(1) if neq else ''}", "points": points}
    if inc and int(inc.group(1)) != 0:
        return {"status": "failed", "detail": f"incomplete verification items: {inc.group(1)}", "points": points}
    if (neq and int(neq.group(1)) > 0) or (ab and int(ab.group(1)) > 0):
        return {"status": "failed", "detail": "non-equivalent or aborted points", "points": points}
    if points == 0:
        return {"status": "error", "detail": "no compared points", "points": points}
    return {"status": "passed", "detail": f"Conformal PASS ({points} equivalent points)", "points": points}


def rtl_sim_check(ctx: FlowContext, design: Sequence[str], testbench: str, pass_marker: str, fail_marker: str,
                  work: Path, timeout: Optional[int] = None) -> Dict[str, object]:
    """Self-checking RTL simulation (explicitly selected verification mode)."""
    work.mkdir(parents=True, exist_ok=True)
    _clear(work, ["sim_check.log", "simv_chk", "simv_chk.daidir", "csrc"])
    extra = [f"+incdir+{d}" for d in ctx.include_dirs]
    extra += [f"+define+{k}={v}" if v not in (None, "") else f"+define+{k}" for k, v in ctx.defines.items()]
    r = ctx.tools.run("simulation", ["-full64", "-sverilog", "+v2k", "-timescale=1ns/1ps", "-o", "simv_chk",
                                     *extra, *design, testbench], work, work / "vcs_check_compile.log", timeout,
                      label="sim_check_compile")
    if r.status == "unavailable":
        return {"status": "unavailable", "detail": r.detail}
    if r.status == "timeout":
        return {"status": "error", "detail": "simulation compile timed out"}
    if not r.ok:
        log = Path(r.log).read_text(errors="replace") if r.log and Path(r.log).is_file() else ""
        if re.search(r"licen[sc]e", log, re.I) and re.search(r"error|fail|unable|could not", log, re.I):
            return {"status": "error", "detail": "simulator license problem (not a candidate failure)"}
        return {"status": "failed", "detail": "candidate failed to compile with checking testbench"}
    r2 = _shell(ctx, work, "./simv_chk -l sim_check.log", work / "vcs_check_run.log", timeout, "sim_check", "simulation")
    if r2.status == "timeout":
        return {"status": "error", "detail": "checking simulation timed out"}
    txt = (work / "sim_check.log").read_text(errors="replace") if (work / "sim_check.log").is_file() else ""
    if fail_marker in txt:
        return {"status": "failed", "detail": f"testbench reported {fail_marker}"}
    if pass_marker in txt and r2.ok:
        return {"status": "passed", "detail": f"testbench printed {pass_marker}"}
    return {"status": "failed", "detail": f"pass marker {pass_marker!r} not found"}


# ------------------------------------------------- external (open) adapters
#
# ``external-ppa`` and ``external-check`` delegate a stage to a user program
# with a fixed file contract, so a site without the commercial tools can
# measure and verify with its own flow (e.g. Yosys + ABC + OpenSTA).
#
# external-ppa:   <exe> [args] --top T --period-ns P --sdc FILE --out DIR
#                 --threads N [--clock-port PORT] [--include-dir D]...
#                 [--define K=V]... -- RTL...
#   must exit 0 and write DIR/metrics.json:
#     {"area_um2": float, "delay_ns": float, "slack_ns": float,
#      "power_uW": float (optional; required for full-ppa), "source": str,
#      "netlist": path (optional)}
#   All metrics are reported at stage "post-synthesis"; P&R, SDF activity and
#   PrimeTime are not run.
# external-check: <exe> [args] --top T --work DIR --golden RTL... --revised RTL...
#   must exit 0 and write DIR/verdict.json:
#     {"status": "passed"|"failed"|"error", "detail": str}

EXTERNAL_STAGE = "post-synthesis"


