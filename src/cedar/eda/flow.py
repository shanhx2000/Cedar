"""DC -> Innovus -> gate-level activity simulation -> PrimeTime, and Conformal.

Adapters generate tool scripts from the technology profile and design spec.
One generated SDC (library time units) is used by every stage so the baseline
and every candidate are measured under identical constraints. Site-specific
behaviour is added through the documented Tcl hooks in the technology profile.

Measurement convention (``full-ppa``, matching the paper's setup):

* area  — DC post-synthesis total cell area (um2)
* delay — DC post-synthesis critical-path data arrival time (ns)
* slack / timing_met — DC post-synthesis worst slack against the declared clock
* power — PrimeTime averaged total power on the post-route netlist with SPEF
  parasitics and SAIF activity from SDF-annotated gate-level simulation (uW)
"""

